"""Build shipped images and launcher icons from the designer's asset pack.

Usage (from the repo root):
    python -I tool/build_assets.py --pack path/to/asset-pack-original

The pack (PNG originals, ~12 MB) is kept outside the repo; this writes:
- assets/illustrations/reading.webp  1080 px wide
- assets/illustrations/*.svg         copied as-is
- Android adaptive launcher icon: the full-bleed icon is the *background*
  layer (108 dp per density) with a transparent foreground, as the pack's
  notes ask (it has no separate foreground/monochrome layers); legacy
  48 dp ic_launcher.png per density for completeness
- iOS AppIcon.appiconset PNGs (no alpha) at every size Contents.json lists
"""

import argparse
import json
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
RES = ROOT / "android" / "app" / "src" / "main" / "res"
IOS_ICONS = ROOT / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset"

ILLUSTRATION_PX = 1080
WEBP_QUALITY = 80

# Android density buckets: scale relative to mdpi.
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/build_assets.py. The designer's icon is full-bleed, so
     it is the background layer; the foreground stays transparent. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@android:color/transparent" />
</adaptive-icon>
"""


def resized(img, width):
    height = round(img.height * width / img.width)
    return img.resize((width, height), Image.LANCZOS)


def save_webp(img, path, width):
    path.parent.mkdir(parents=True, exist_ok=True)
    resized(img.convert("RGB"), width).save(path, "WEBP", quality=WEBP_QUALITY, method=6)
    return path.stat().st_size


def build_images(pack):
    total = 0
    # Article covers are drawn in-app as book jackets (ArticleCover); the
    # pack's category covers are no longer bundled.
    total += save_webp(
        Image.open(pack / "illustrations" / "reading.png"),
        ASSETS / "illustrations" / "reading.webp",
        ILLUSTRATION_PX,
    )
    for svg in (pack / "illustrations").glob("*.svg"):
        shutil.copyfile(svg, ASSETS / "illustrations" / svg.name)
    return total


# Launchers show only the middle 72 of the adaptive icon's 108 dp and then
# mask it (circle, squircle...). The pack's icon is full-bleed with a large
# motif, so it is shrunk onto its own background colour to keep the motif
# inside the safe zone.
ADAPTIVE_ICON_SCALE = 0.8


def adaptive_background(icon, px):
    canvas = Image.new("RGB", (px, px), icon.getpixel((4, 4)))
    inner = round(px * ADAPTIVE_ICON_SCALE)
    canvas.paste(icon.resize((inner, inner), Image.LANCZOS), ((px - inner) // 2,) * 2)
    return canvas


def build_android_icon(icon):
    for name, scale in DENSITIES.items():
        folder = RES / f"mipmap-{name}"
        folder.mkdir(parents=True, exist_ok=True)
        adaptive_background(icon, round(108 * scale)).save(folder / "ic_launcher_background.png")
        icon.resize((round(48 * scale),) * 2, Image.LANCZOS).save(folder / "ic_launcher.png")
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(ADAPTIVE_XML, encoding="utf-8")


def build_ios_icon(icon):
    contents = json.loads((IOS_ICONS / "Contents.json").read_text(encoding="utf-8"))
    for entry in contents["images"]:
        points = float(entry["size"].split("x")[0])
        scale = int(entry["scale"].rstrip("x"))
        px = round(points * scale)
        icon.resize((px, px), Image.LANCZOS).save(IOS_ICONS / entry["filename"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--pack", required=True, type=Path, help="asset pack folder")
    args = parser.parse_args()

    total = build_images(args.pack)
    # iOS rejects icons with alpha; the pack's icon is RGB already, enforce it.
    icon = Image.open(args.pack / "brand" / "app-icon-1024.png").convert("RGB")
    build_android_icon(icon)
    build_ios_icon(icon)
    print(f"images: {total // 1024} KB total; launcher icons written")


if __name__ == "__main__":
    main()
